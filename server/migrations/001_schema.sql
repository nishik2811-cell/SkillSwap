-- SkillSwap schema for PostgreSQL (squashed from the original 12 MySQL migrations).
-- Money is integer paise. Times are timestamptz (UTC). Constraint/index names match the MySQL version because the code checks some of them.
CREATE EXTENSION IF NOT EXISTS citext;

-- like MySQL's ON UPDATE CURRENT_TIMESTAMP: refresh only when the statement did not set updated_at itself
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$ BEGIN IF NEW.updated_at IS NOT DISTINCT FROM OLD.updated_at THEN NEW.updated_at = NOW(); END IF; RETURN NEW; END; $$ LANGUAGE plpgsql;

CREATE TABLE platform_settings ("key" VARCHAR(64) PRIMARY KEY, value VARCHAR(2000) NOT NULL);

-- ---------- identity ----------
CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email CITEXT NOT NULL,
  username CITEXT NOT NULL,                       -- citext: "Nish" and "nish" collide, like the old case-insensitive collation
  password_hash VARCHAR(255) NOT NULL,
  full_name VARCHAR(100) NOT NULL,
  role TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('user','admin')),
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','suspended','deactivated')),
  email_verified_at TIMESTAMPTZ NULL,
  avatar_path VARCHAR(255) NULL,
  bio VARCHAR(500) NULL,
  age SMALLINT NULL,
  location VARCHAR(100) NULL,
  timezone VARCHAR(64) NULL,
  preferred_language VARCHAR(40) NULL,
  onboarding_done BOOLEAN NOT NULL DEFAULT FALSE,
  last_active_at TIMESTAMPTZ NULL,
  rating_avg NUMERIC(3,2) NULL,
  rating_count INT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_users_email UNIQUE (email),
  CONSTRAINT uq_users_username UNIQUE (username),
  CONSTRAINT ck_users_username CHECK (username::text ~ '^[a-z0-9_]{3,20}$'),
  CONSTRAINT ck_users_age CHECK (age IS NULL OR age BETWEEN 13 AND 120)
);
CREATE INDEX ix_users_active ON users (status, onboarding_done, last_active_at);
CREATE TRIGGER trg_users_updated BEFORE UPDATE ON users FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE auth_sessions (
  token_hash CHAR(64) PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX ix_auth_sessions_user ON auth_sessions (user_id);

CREATE TABLE email_tokens (
  token_hash CHAR(64) PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  purpose TEXT NOT NULL CHECK (purpose IN ('verify_email','reset_password')),
  expires_at TIMESTAMPTZ NOT NULL,
  used_at TIMESTAMPTZ NULL
);

-- ---------- skills & preferences ----------
CREATE TABLE categories (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(60) NOT NULL UNIQUE);
CREATE TABLE skills (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id INT NOT NULL REFERENCES categories(id),
  name VARCHAR(80) NOT NULL UNIQUE
);
CREATE INDEX ix_skills_category ON skills (category_id);

CREATE TABLE mentor_skills (
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  skill_id INT NOT NULL REFERENCES skills(id),
  level TEXT NOT NULL CHECK (level IN ('beginner','intermediate','advanced','expert')),
  years_experience SMALLINT NULL,
  pricing TEXT NOT NULL DEFAULT 'free' CHECK (pricing IN ('free','paid','both')),
  price_min_paise INT NULL,
  price_max_paise INT NULL,
  teaching_style TEXT NOT NULL DEFAULT 'one_on_one' CHECK (teaching_style IN ('one_on_one','group','workshop','interactive')),
  PRIMARY KEY (user_id, skill_id),
  CONSTRAINT ck_mentor_price CHECK (
    (pricing = 'free' AND price_min_paise IS NULL AND price_max_paise IS NULL)
    OR (pricing <> 'free' AND price_min_paise IS NOT NULL AND price_max_paise IS NOT NULL AND price_min_paise <= price_max_paise))
);
CREATE INDEX ix_mentor_skills_skill ON mentor_skills (skill_id);

CREATE TABLE learner_skills (
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  skill_id INT NOT NULL REFERENCES skills(id),
  current_level TEXT NOT NULL DEFAULT 'none' CHECK (current_level IN ('none','beginner','intermediate','advanced')),
  desired_level TEXT NULL CHECK (desired_level IN ('beginner','intermediate','advanced','expert')),
  prefers TEXT NOT NULL DEFAULT 'either' CHECK (prefers IN ('free','paid','either')),
  max_price_paise INT NULL,
  learning_style TEXT NOT NULL DEFAULT 'one_on_one' CHECK (learning_style IN ('one_on_one','group','workshop','interactive')),
  PRIMARY KEY (user_id, skill_id)
);
CREATE INDEX ix_learner_skills_skill ON learner_skills (skill_id);

CREATE TABLE availability_slots (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  weekday SMALLINT NOT NULL,
  start_time TIME NOT NULL,
  end_time TIME NOT NULL,
  CONSTRAINT ck_slot CHECK (weekday <= 6 AND start_time < end_time)
);
CREATE INDEX ix_slots_user_day ON availability_slots (user_id, weekday);

CREATE TABLE user_languages (
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  language VARCHAR(40) NOT NULL,
  PRIMARY KEY (user_id, language)
);

-- ---------- social ----------
CREATE TABLE blocks (
  blocker_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  blocked_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (blocker_id, blocked_id),
  CONSTRAINT ck_no_self_block CHECK (blocker_id <> blocked_id)
);

CREATE TABLE discovery_impressions (
  viewer_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  shown_count INT NOT NULL DEFAULT 1,
  last_shown_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (viewer_id, user_id)
);

CREATE TABLE connections (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  requester_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  addressee_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  user_lo BIGINT GENERATED ALWAYS AS (LEAST(requester_id, addressee_id)) STORED,
  user_hi BIGINT GENERATED ALWAYS AS (GREATEST(requester_id, addressee_id)) STORED,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','accepted','rejected')),
  message VARCHAR(300) NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  responded_at TIMESTAMPTZ NULL,
  CONSTRAINT uq_connection_pair UNIQUE (user_lo, user_hi),       -- one row per pair, whichever side asked first
  CONSTRAINT ck_no_self_conn CHECK (requester_id <> addressee_id)
);
CREATE INDEX ix_conn_addressee ON connections (addressee_id, status);

CREATE TABLE reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reporter_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  target_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  session_id BIGINT NULL,                                          -- FK added below (sessions table comes later)
  reason TEXT NOT NULL CHECK (reason IN ('spam','harassment','inappropriate','fake_profile','scam','other')),
  details VARCHAR(1000) NULL,
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','resolved','dismissed')),
  resolution_note VARCHAR(500) NULL,
  resolved_by BIGINT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  resolved_at TIMESTAMPTZ NULL,
  CONSTRAINT ck_no_self_report CHECK (reporter_id <> target_user_id)
);
CREATE INDEX ix_reports_status ON reports (status, created_at);

CREATE TABLE notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  type VARCHAR(40) NOT NULL,
  title VARCHAR(160) NOT NULL,
  body VARCHAR(300) NULL,
  link VARCHAR(200) NULL,
  read_at TIMESTAMPTZ NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX ix_notif_user ON notifications (user_id, read_at, created_at);

-- ---------- chat ----------
CREATE TABLE conversations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type TEXT NOT NULL CHECK (type IN ('direct','group')),
  title VARCHAR(80) NULL,
  created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  direct_key VARCHAR(41) NULL,
  last_message_at TIMESTAMPTZ NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_direct_key UNIQUE (direct_key),
  CONSTRAINT ck_conv_shape CHECK ((type = 'direct' AND direct_key IS NOT NULL AND title IS NULL) OR (type = 'group' AND direct_key IS NULL AND title IS NOT NULL))
);
CREATE TABLE conversation_members (
  conversation_id BIGINT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  role TEXT NOT NULL DEFAULT 'member' CHECK (role IN ('admin','member')),
  joined_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  last_read_message_id BIGINT NULL,
  PRIMARY KEY (conversation_id, user_id)
);
CREATE INDEX ix_members_user ON conversation_members (user_id);
CREATE TABLE messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id BIGINT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
  sender_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  kind TEXT NOT NULL DEFAULT 'text' CHECK (kind IN ('text','system')),
  body VARCHAR(4000) NULL,
  deleted_at TIMESTAMPTZ NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX ix_messages_conv ON messages (conversation_id, id);
CREATE TABLE attachments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id BIGINT NOT NULL REFERENCES messages(id) ON DELETE CASCADE,
  original_name VARCHAR(200) NOT NULL,
  stored_path VARCHAR(120) NOT NULL,
  mime VARCHAR(100) NOT NULL,
  size INT NOT NULL
);

-- ---------- learning sessions, bookings, reviews ----------
CREATE TABLE learning_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mentor_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  skill_id INT NOT NULL REFERENCES skills(id),
  title VARCHAR(120) NOT NULL,
  description VARCHAR(2000) NULL,
  starts_at TIMESTAMPTZ NOT NULL,
  duration_min SMALLINT NOT NULL,
  capacity SMALLINT NOT NULL DEFAULT 1,
  pricing TEXT NOT NULL DEFAULT 'free' CHECK (pricing IN ('free','paid')),
  price_paise INT NULL,
  auto_accept BOOLEAN NOT NULL DEFAULT FALSE,
  status TEXT NOT NULL DEFAULT 'scheduled' CHECK (status IN ('scheduled','cancelled','completed')),
  cancel_reason VARCHAR(300) NULL,
  reminder_sent BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT ck_session_capacity CHECK (capacity BETWEEN 1 AND 100),
  CONSTRAINT ck_session_duration CHECK (duration_min BETWEEN 15 AND 480),
  CONSTRAINT ck_session_price CHECK ((pricing = 'free' AND price_paise IS NULL) OR (pricing = 'paid' AND price_paise > 0))
);
CREATE INDEX ix_sessions_upcoming ON learning_sessions (status, starts_at);
CREATE INDEX ix_sessions_mentor ON learning_sessions (mentor_id, starts_at);
CREATE TRIGGER trg_sessions_updated BEFORE UPDATE ON learning_sessions FOR EACH ROW EXECUTE FUNCTION set_updated_at();
ALTER TABLE reports ADD CONSTRAINT fk_reports_session FOREIGN KEY (session_id) REFERENCES learning_sessions(id) ON DELETE SET NULL;

CREATE TABLE bookings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id BIGINT NOT NULL REFERENCES learning_sessions(id) ON DELETE CASCADE,
  learner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  status TEXT NOT NULL DEFAULT 'requested' CHECK (status IN ('requested','awaiting_payment','confirmed','rejected','cancelled','completed')),
  note VARCHAR(300) NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_booking UNIQUE (session_id, learner_id)
);
CREATE INDEX ix_bookings_learner ON bookings (learner_id, status);
CREATE TRIGGER trg_bookings_updated BEFORE UPDATE ON bookings FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE reviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id BIGINT NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  reviewer_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  reviewee_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  reviewee_role TEXT NOT NULL DEFAULT 'mentor' CHECK (reviewee_role IN ('mentor','learner')),
  rating SMALLINT NOT NULL,
  comment VARCHAR(1000) NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_review UNIQUE (booking_id, reviewer_id),
  CONSTRAINT ck_rating CHECK (rating BETWEEN 1 AND 5),
  CONSTRAINT ck_no_self_review CHECK (reviewer_id <> reviewee_id)
);
CREATE INDEX ix_reviews_role ON reviews (reviewee_id, reviewee_role, id);

-- ---------- payments (financial rows are RESTRICTed: they never vanish with a user or booking) ----------
CREATE TABLE payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id BIGINT NOT NULL REFERENCES bookings(id) ON DELETE RESTRICT,
  learner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  mentor_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  amount_paise INT NOT NULL,
  currency CHAR(3) NOT NULL DEFAULT 'INR',
  commission_percent NUMERIC(5,2) NOT NULL,
  platform_fee_paise INT NOT NULL,
  mentor_net_paise INT NOT NULL,
  status TEXT NOT NULL DEFAULT 'created' CHECK (status IN ('created','paid','failed','refunded')),
  gateway_order_id VARCHAR(64) NOT NULL,
  gateway_payment_id VARCHAR(64) NULL,
  method VARCHAR(30) NULL,
  failure_reason VARCHAR(300) NULL,
  paid_at TIMESTAMPTZ NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_gateway_order UNIQUE (gateway_order_id),
  CONSTRAINT uq_gateway_payment UNIQUE (gateway_payment_id),
  CONSTRAINT ck_payment_split CHECK (platform_fee_paise + mentor_net_paise = amount_paise AND amount_paise > 0)
);
CREATE UNIQUE INDEX uq_one_paid_per_booking ON payments (booking_id) WHERE status = 'paid';           -- a booking can't be paid twice
CREATE UNIQUE INDEX uq_one_open_payment ON payments (booking_id) WHERE status IN ('created','failed'); -- one open attempt per booking
CREATE INDEX ix_payments_learner ON payments (learner_id, created_at);
CREATE INDEX ix_payments_mentor ON payments (mentor_id, status);
CREATE TRIGGER trg_payments_updated BEFORE UPDATE ON payments FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE refunds (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_id BIGINT NOT NULL REFERENCES payments(id) ON DELETE RESTRICT,
  amount_paise INT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','processed','failed')),
  gateway_refund_id VARCHAR(64) NULL,
  reason VARCHAR(200) NOT NULL,
  initiated_by TEXT NOT NULL CHECK (initiated_by IN ('learner','mentor','admin','system')),
  failure_reason VARCHAR(300) NULL,
  attempts SMALLINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  processed_at TIMESTAMPTZ NULL,
  CONSTRAINT uq_gateway_refund UNIQUE (gateway_refund_id),
  CONSTRAINT ck_refund_amount CHECK (amount_paise > 0)
);
CREATE INDEX ix_refunds_status ON refunds (status, created_at);

CREATE TABLE webhook_events (event_id VARCHAR(100) PRIMARY KEY, type VARCHAR(60) NOT NULL, received_at TIMESTAMPTZ NOT NULL DEFAULT NOW());

CREATE TABLE payouts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mentor_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  amount_paise INT NOT NULL,
  destination VARCHAR(120) NOT NULL,
  status TEXT NOT NULL DEFAULT 'requested' CHECK (status IN ('requested','paid','rejected')),
  admin_note VARCHAR(300) NULL,
  requested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  processed_at TIMESTAMPTZ NULL,
  CONSTRAINT ck_payout_amount CHECK (amount_paise > 0)
);
CREATE INDEX ix_payouts_status ON payouts (status, requested_at);

-- ---------- meetings ----------
CREATE TABLE meeting_rooms (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(14) NOT NULL,
  session_id BIGINT NULL REFERENCES learning_sessions(id) ON DELETE SET NULL,
  host_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title VARCHAR(120) NOT NULL,
  waiting_room BOOLEAN NOT NULL DEFAULT TRUE,
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','ended')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  ended_at TIMESTAMPTZ NULL,
  CONSTRAINT uq_room_code UNIQUE (code),
  CONSTRAINT uq_room_session UNIQUE (session_id)
);
CREATE TABLE meeting_participants (
  room_id BIGINT NOT NULL REFERENCES meeting_rooms(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  role TEXT NOT NULL DEFAULT 'participant' CHECK (role IN ('host','cohost','participant')),
  status TEXT NOT NULL CHECK (status IN ('waiting','admitted','denied','left','removed')),
  first_joined_at TIMESTAMPTZ NULL,
  last_left_at TIMESTAMPTZ NULL,
  requested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (room_id, user_id)
);
CREATE INDEX ix_mp_user ON meeting_participants (user_id, requested_at);

-- ---------- admin ----------
CREATE TABLE admin_actions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  admin_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  action VARCHAR(60) NOT NULL,
  target_type VARCHAR(30) NOT NULL,
  target_id BIGINT NULL,
  note VARCHAR(500) NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX ix_admin_actions ON admin_actions (created_at);
CREATE TABLE disputes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_id BIGINT NOT NULL REFERENCES payments(id) ON DELETE RESTRICT,
  opened_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  reason VARCHAR(1000) NOT NULL,
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','refunded','rejected')),
  admin_note VARCHAR(500) NULL,
  resolved_by BIGINT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  resolved_at TIMESTAMPTZ NULL
);
CREATE UNIQUE INDEX uq_one_open_dispute ON disputes (payment_id) WHERE status = 'open';
CREATE INDEX ix_disputes_status ON disputes (status, created_at);

